"""Derive descriptive paper tables from the preserved reconstruction results."""

import argparse
from collections import Counter
import csv
import hashlib
import json
from pathlib import Path
import statistics


def identity(path):
    data = path.read_bytes()
    return {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def describe(values):
    return ({"n": len(values), "minimum": min(values), "median": statistics.median(values),
             "maximum": max(values), "sum": sum(values)} if values else {"n": 0})


def summarize(evidence, output):
    output.mkdir(parents=True, exist_ok=True)
    paths = {"holdout": evidence / "holdout/results.json",
             "mutations": evidence / "mutations/results.json",
             "controls": evidence / "controls/independent-control-audit.json"}
    inputs = {name: json.loads(path.read_text()) for name, path in paths.items()}
    holdout = inputs["holdout"]
    result = {"schema": "replicate-paper-descriptive-tables-v1",
              "source_results": {name: identity(path) for name, path in paths.items()},
              "statistical_inference_claimed": False,
              "holdout": {}, "controls": inputs["controls"],
              "mutations": {key: inputs["mutations"][key] for key in (
                  "native_births", "valid_controls", "valid_controls_accepted",
                  "invalid_variants", "invalid_variants_rejected",
                  "false_rejections", "false_acceptances")}}
    flat = []
    for arm, specification in holdout["arms"].items():
        rows = specification["cases"]
        result["holdout"][arm] = {
            "successes": sum(r["passed"] for r in rows), "planned_cases": len(rows),
            "by_family": specification["by_family"],
            "failure_conditions": dict(Counter(r["condition"] for r in rows if not r["passed"])),
            "all_case_seconds": describe([r["seconds"] for r in rows if "seconds" in r]),
            "model_calls": sum(r.get("model_calls", 0) for r in rows),
            "tool_calls": sum(r.get("tool_calls", 0) for r in rows),
            "timing_boundary": "solver only" if arm == "fixed-policy" else "application RPC and polling",
        }
        flat.extend(dict(arm=arm, **row) for row in rows)
    by_arm = {arm: {r["case_id"]: r for r in spec["cases"]}
              for arm, spec in holdout["arms"].items()}
    paired = Counter()
    for case_id in by_arm["trained-merged"]:
        trained = by_arm["trained-merged"][case_id]["passed"]
        stock = by_arm["stock-control"][case_id]["passed"]
        paired[("trained_pass" if trained else "trained_fail") + "__" +
               ("stock_pass" if stock else "stock_fail")] += 1
    result["paired_trained_stock"] = dict(paired)
    fields = ["arm", "case_id", "family", "condition", "passed", "trace_audit_passed",
              "seconds", "model_calls", "tool_calls", "failure", "missing"]
    with (output / "holdout-cases.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(flat)
    (output / "paper-summary.json").write_text(json.dumps(result, indent=2) + "\n")
    names = {"fixed-policy": "Fixed policy", "stock-control": "Stock model",
             "trained-merged": "Trained model"}
    latex = ["% Generated by organism.research.summarize_paper; descriptive counts only."]
    for arm, value in result["holdout"].items():
        latex.append(f"{names[arm]} & {value['successes']}/{value['planned_cases']} & "
                     f"{value['model_calls']} & {value['all_case_seconds']['median']:.5f}" + r"\\")
    (output / "holdout-table-rows.tex").write_text("\n".join(latex) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(summarize(args.evidence.resolve(), args.output.resolve()), indent=2))
